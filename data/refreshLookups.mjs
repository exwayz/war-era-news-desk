// Regenerates data/offlineLookups.js from the live War Era API so offline
// name resolution stays current as game data changes.
//
// Usage (API key is read from the environment, never hardcoded):
//   WAE_KEY=wae_... node data/refreshLookups.mjs

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(__dirname, "offlineLookups.js");

const K = process.env.WAE_KEY;
if (!K) {
  console.error("Set WAE_KEY=<api-key> before running.");
  process.exit(1);
}

const GATEWAY = "https://gateway.warerastats.io/trpc";
const API2 = "https://api2.warera.io/trpc";

async function call(base, method, input, headers) {
  const url = `${base}/${method}?input=${encodeURIComponent(JSON.stringify(input))}`;
  const r = await fetch(url, { headers });
  if (!r.ok) throw new Error(`${method} ${r.status} ${(await r.text()).slice(0, 120)}`);
  return JSON.parse(await r.text());
}

const unwrap = (r) => Array.isArray(r)
  ? r[0]?.result?.data?.json ?? r[0]?.result?.data ?? r[0]?.json ?? r[0]
  : r?.result?.data?.json ?? r?.result?.data ?? r?.json ?? r;

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function paginate(base, method, input, headers, pickName, maxPages = 200) {
  const map = {};
  let cursor;
  for (let page = 0; page < maxPages; page++) {
    const pageInput = { ...input };
    if (cursor) pageInput.cursor = cursor;
    const d = unwrap(await call(base, method, pageInput, headers));
    const items = Array.isArray(d) ? d : (d?.items || []);
    if (!items.length) break;
    for (const it of items) {
      const id = it._id || it.id;
      const name = pickName(it);
      if (id && name) map[id] = name;
    }
    cursor = d?.nextCursor || d?.cursor || null;
    if (!cursor) break;
    if (page % 10 === 9) await sleep(300);
  }
  return map;
}

function writeSection(js, key, map) {
  js += `  ${key}: {\n`;
  for (const [id, name] of Object.entries(map).sort((a, b) => a[1].localeCompare(b[1]))) {
    js += `    ${JSON.stringify(id)}: ${JSON.stringify(name)},\n`;
  }
  js += "  },\n";
  return js;
}

const headers = { "x-api-key": K };
const headers2 = { "X-API-Key": K };

const countries = {};
for (const c of unwrap(await call(GATEWAY, "country.getAllCountries", {}, headers))) {
  const id = c._id || c.id;
  if (id && c.name) countries[id] = c.name;
}
console.log(`countries: ${Object.keys(countries).length}`);

const regions = {};
const regionsObj = unwrap(await call(GATEWAY, "region.getRegionsObject", {}, headers));
for (const [id, r] of Object.entries(regionsObj)) {
  const name = r.name || r.mainCity;
  if (id && name) regions[id] = name;
}
console.log(`regions: ${Object.keys(regions).length}`);

const alliances = await paginate(API2, "alliance.getManyPaginated", { limit: 100 }, headers2, (a) => a.name);
console.log(`alliances: ${Object.keys(alliances).length}`);

const parties = await paginate(API2, "party.getManyPaginated", { limit: 100 }, headers2, (p) => p.name);
console.log(`parties: ${Object.keys(parties).length}`);

const mus = await paginate(GATEWAY, "mu.getManyPaginated", { limit: 100 }, headers, (m) => m.name);
console.log(`mus: ${Object.keys(mus).length}`);

let js = "// Auto-generated by refreshLookups.mjs - do not edit by hand.\n";
js += "// Run: WAE_KEY=<api-key> node data/refreshLookups.mjs\n";
js += "export const offlineLookups = {\n";
js = writeSection(js, "countries", countries);
js = writeSection(js, "regions", regions);
js = writeSection(js, "alliances", alliances);
js = writeSection(js, "parties", parties);
js = writeSection(js, "mus", mus);
js += "};\n";

fs.writeFileSync(OUT, js, "utf8");
console.log(`Wrote ${OUT}`);
