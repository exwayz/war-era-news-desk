// Builds data/userLookups.js — an id→username map of every War Era player,
// used by the Article Jotter's @user mention suggestions.
//
// Usage (API key read from env, never hardcoded):
//   WAE_KEY=wae_... node data/fetchUserLookups.mjs
//
// Notes: user.getUsersByCountry returns only _id + createdAt, so every user id
// needs its own user.getUserLite call for the username (token limit ~500/min).

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(__dirname, "userLookups.js");

const K = process.env.WAE_KEY;
if (!K) {
  console.error("Set WAE_KEY=<api-key> before running.");
  process.exit(1);
}

const GATEWAY = "https://gateway.warerastats.io/trpc";
const API2 = "https://api2.warera.io/trpc";
const PAGE_SIZE = 100;
const CONCURRENCY = 20;
const MIN_INTERVAL_MS = 125;
const MAX_RETRIES = 3;

async function call(base, method, input, headers, tries = 3) {
  for (let t = 1; t <= tries; t++) {
    try {
      const url = `${base}/${method}?input=${encodeURIComponent(JSON.stringify(input))}`;
      const r = await fetch(url, { headers });
      if (r.ok) return JSON.parse(await r.text());
      if (r.status === 429 || r.status >= 500) {
        await new Promise((res) => setTimeout(res, 2000 * t));
        continue;
      }
      throw new Error(`${method} ${r.status} ${(await r.text()).slice(0, 120)}`);
    } catch (e) {
      if (t === tries) throw e;
      await new Promise((res) => setTimeout(res, 1000 * t));
    }
  }
  throw new Error(`${method} failed`);
}

const unwrap = (r) => (Array.isArray(r)
  ? r[0]?.result?.data?.json ?? r[0]?.result?.data ?? r[0]?.json ?? r[0]
  : r?.result?.data?.json ?? r?.result?.data ?? r?.json ?? r);

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

let lastRequestAt = 0;
async function throttled(fn) {
  const now = Date.now();
  const wait = Math.max(0, lastRequestAt + MIN_INTERVAL_MS - now);
  lastRequestAt = Math.max(now, lastRequestAt + MIN_INTERVAL_MS);
  if (wait > 0) await sleep(wait);
  return fn();
}

async function mapLimit(items, limit, fn) {
  const results = new Array(items.length);
  let idx = 0;
  const workers = Array.from({ length: Math.min(limit, items.length) }, async () => {
    while (idx < items.length) {
      const i = idx++;
      results[i] = await fn(items[i]);
    }
  });
  await Promise.all(workers);
  return results;
}

(async () => {
  const headersGw = { "x-api-key": K };
  const headers2 = { "X-API-Key": K };

  const countries = unwrap(await call(GATEWAY, "country.getAllCountries", {}, headersGw));
  console.log(`countries: ${countries.length}`);

  const byId = new Map();
  for (const c of countries) {
    let cursor = null;
    for (let p = 0; p < 500; p++) {
      const body = await throttled(() => call(API2, "user.getUsersByCountry",
        cursor ? { countryId: c._id, limit: PAGE_SIZE, cursor } : { countryId: c._id, limit: PAGE_SIZE },
        headers2));
      const data = unwrap(body);
      const batch = data?.items || [];
      for (const u of batch) byId.set(u._id, u.createdAt);
      if (!data?.nextCursor || data.nextCursor === cursor) break;
      cursor = data.nextCursor;
    }
    console.log(`  ${c.code}: ${byId.size} users so far`);
  }

  const ids = [...byId.keys()];
  console.log(`total users: ${ids.length}, fetching usernames...`);

  const results = await mapLimit(ids, CONCURRENCY, async (userId) => {
    for (let attempt = 0; attempt < MAX_RETRIES; attempt++) {
      try {
        const d = unwrap(await throttled(() => call(API2, "user.getUserLite", { userId }, headers2)));
        const name = d?.username || d?.userName || null;
        if (name) return { id: userId, username: name };
        return { id: userId, username: null };
      } catch (e) {
        if (attempt === MAX_RETRIES - 1) {
          console.error(`  failed ${userId}: ${e.message}`);
          return { id: userId, username: null };
        }
        await sleep(500 * (attempt + 1));
      }
    }
    return { id: userId, username: null };
  });

  const users = results.filter((u) => u.username);
  users.sort((a, b) => a.username.localeCompare(b.username) || a.id.localeCompare(b.id));

  let js = "// Auto-generated by fetchUserLookups.mjs - do not edit by hand.\n";
  js += "// Run: WAE_KEY=<api-key> node data/fetchUserLookups.mjs\n";
  js += "export const userLookups = {\n  users: {\n";
  for (const u of users) {
    js += `    ${JSON.stringify(u.id)}: ${JSON.stringify(u.username)},\n`;
  }
  js += "  },\n};\n";
  fs.writeFileSync(OUT, js, "utf8");
  console.log(`Wrote ${OUT} (${users.length} users, ${(js.length / 1024).toFixed(0)} KB)`);
})().catch((e) => { console.error(e); process.exit(1); });